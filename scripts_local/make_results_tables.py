def table_row(method, keep):
    vals = TABLE_ROWS[(method, keep)].split()
    out = dict(zip(TASKS, vals))
    for t in ("coco_cap", "nocaps", "textcaps"):
        out[t] = f"{out[t]} / –"
    return out


def merged(*parts):
    """parts: (roots, tasks) pairs; later parts fill only their own tasks."""
    row = {}
    for roots, tasks in parts:
        vals, _ = collect(*roots, tasks=tasks)
        row.update(vals)
    return row


def render(title, rows, pending_tasks=None):
    pending_tasks = pending_tasks or {}
    lines = [f"### {title}", "", "| Method | " + " | ".join(HEAD[t] for t in TASKS) + " |",
             "|---|" + "---|" * len(TASKS)]
    for name, row in rows:
        cells = []
        for t in TASKS:
            v = row.get(t)
            if v is None:
                v = PENDING if t in pending_tasks.get(name, ()) else "--"
            cells.append(v)
        lines.append(f"| {name} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


